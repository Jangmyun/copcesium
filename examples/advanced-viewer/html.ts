/** Escapes text for interpolation into an HTML template, so a value that
 *  doesn't come from this file's own constants (a CRS string, a dataset
 *  label, a measured number) can never be parsed as markup. */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
